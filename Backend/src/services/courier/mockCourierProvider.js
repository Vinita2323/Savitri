import crypto from 'crypto';
import { chargeableWeightKg, calculateShippingCharge } from './shippingCalculator.js';

// SIMULATED courier. Everything here is invented test data for development; every response carries
// simulated:true and a SIMULATED label. Never used when NODE_ENV=production (courierService enforces it).
//
// Simulated coverage rules (NOT real - chosen only so both outcomes can be tested):
//   - PIN codes starting 19 or 79 are "remote": no courier serves them.
//   - Parcels above 30 kg chargeable are refused.
//   - COD is unavailable for PIN codes ending in 7.
// Simulated zones: same first 3 digits = A (local), same first digit = B (regional), otherwise C (national).
const MAX_KG = 30;
const TEST_RATES = { // TEST RATES - not real courier prices
  A: { firstSlabCharge: 30, additionalSlabCharge: 15 },
  B: { firstSlabCharge: 45, additionalSlabCharge: 20 },
  C: { firstSlabCharge: 60, additionalSlabCharge: 28 },
};
const COURIERS = [
  { courierId: 'MOCK_EXPRESS', courierName: 'MockExpress (simulated)', multiplier: 1.5, etaShift: -1, maxKg: 30 },
  { courierId: 'MOCK_STANDARD', courierName: 'MockStandard (simulated)', multiplier: 1.0, etaShift: 0, maxKg: 30 },
  { courierId: 'MOCK_ECONOMY', courierName: 'MockEconomy (simulated)', multiplier: 0.8, etaShift: 2, maxKg: 5 },
];
const ETA_DAYS = { A: [1, 2], B: [2, 4], C: [4, 7] };

const zoneOf = (from, to) => (from.slice(0, 3) === to.slice(0, 3) ? 'A' : from[0] === to[0] ? 'B' : 'C');
const hash = (s) => crypto.createHash('sha256').update(String(s)).digest('hex');
const SIM = { simulated: true, provider: 'MOCK', notice: 'SIMULATED - test data, not a real courier response' };

export const mockCourierProvider = {
  name: 'mock',
  simulated: true,
  isConfigured: () => true,

  async checkServiceability({ pickupPincode, deliveryPincode, weightKg, length, breadth, height, paymentMethod = 'PREPAID', codAmount = 0 }) {
    const w = chargeableWeightKg({ weightKg, length, breadth, height });
    const base = { ...SIM, chargeableWeightKg: w.chargeableKg, actualWeightKg: w.actualKg, volumetricWeightKg: w.volumetricKg };
    if (/^(19|79)/.test(deliveryPincode) || /^(19|79)/.test(pickupPincode)) {
      return { ...base, serviceable: false, couriers: [], rejectionReason: 'SIMULATED: no courier covers this PIN code (remote area in test rules)' };
    }
    if (w.chargeableKg > MAX_KG) {
      return { ...base, serviceable: false, couriers: [], rejectionReason: `SIMULATED: parcel exceeds the ${MAX_KG} kg test limit` };
    }
    const isCod = String(paymentMethod).toUpperCase() === 'COD';
    if (isCod && deliveryPincode.endsWith('7')) {
      return { ...base, serviceable: false, couriers: [], rejectionReason: 'SIMULATED: COD is not available for this PIN code in test rules' };
    }
    const zone = zoneOf(pickupPincode, deliveryPincode);
    const rate = TEST_RATES[zone];
    const [lo, hi] = ETA_DAYS[zone];
    const couriers = COURIERS.filter((c) => w.chargeableKg <= c.maxKg).map((c) => {
      const charge = calculateShippingCharge({
        chargeableKg: w.chargeableKg,
        rate: { firstSlabCharge: rate.firstSlabCharge * c.multiplier, additionalSlabCharge: rate.additionalSlabCharge * c.multiplier, slabKg: 0.5, fuelPercent: 5, codFlat: 35, codPercent: 2 },
        paymentMethod, codAmount,
      });
      return {
        courierId: c.courierId, courierName: c.courierName, zone,
        estimatedCharge: charge.total, chargeBreakdown: charge,
        etaDaysMin: Math.max(1, lo + c.etaShift), etaDaysMax: Math.max(2, hi + c.etaShift),
        rateType: 'TEST_RATE', simulated: true,
      };
    });
    return { ...base, serviceable: couriers.length > 0, couriers, rejectionReason: couriers.length ? null : 'SIMULATED: no courier available for this parcel' };
  },

  async createShipment({ referenceId, courierId }) {
    const h = hash(referenceId);
    const c = COURIERS.find((x) => x.courierId === courierId) || COURIERS[1];
    return {
      ...SIM, ok: true, courierId: c.courierId, courierName: c.courierName,
      providerOrderId: `MOCK-ORD-${h.slice(0, 8)}`, providerShipmentId: `MOCK-SHP-${h.slice(8, 16)}`,
      awb: `MOCKAWB${h.slice(0, 10).toUpperCase()}`, // deterministic: the same reference always gets the same AWB
      trackingUrl: null, // a real tracking page does not exist for simulated shipments
    };
  },

  async generateLabel({ awb }) {
    return {
      ...SIM, ok: true,
      labelText: `*** SIMULATED SHIPPING LABEL - TEST ONLY - NOT VALID FOR DISPATCH ***\nAWB: ${awb}\nGenerated by the mock courier provider.`,
    };
  },

  async schedulePickup({ providerShipmentId, pickupDate }) {
    const when = pickupDate ? new Date(pickupDate) : new Date(Date.now() + 24 * 3600 * 1000);
    return { ...SIM, ok: true, pickupReference: `MOCK-PCK-${hash(providerShipmentId).slice(0, 8)}`, scheduledAt: when };
  },

  async getTracking() {
    return { ...SIM, ok: true, events: [] }; // events are advanced explicitly through the dev-only simulate endpoint
  },
};

export default mockCourierProvider;
