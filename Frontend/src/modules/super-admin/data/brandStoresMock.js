export const getStoresByBrand = (brandSlug) => {
  if (!brandSlug || brandSlug === 'ALL') return BRAND_STORES;
  return BRAND_STORES.filter((s) => s.brandSlug === brandSlug);
};

export const getStoreById = (storeId) => {
  return BRAND_STORES.find((s) => s.storeId === storeId || s.sellerId === storeId) || null;
};

export const getBrandStoreStats = (brandSlug) => {
  const list = getStoresByBrand(brandSlug);
  const totalStores = list.length;
  const activeStores = list.filter((s) => s.storeStatus === 'Active').length;
  const pendingVerification = list.filter((s) => s.verificationStatus === 'Pending' || s.verificationStatus === 'Under Review').length;
  const inactiveStores = list.filter((s) => s.storeStatus === 'Inactive' || s.storeStatus === 'Suspended').length;

  return {
    totalStores,
    activeStores,
    pendingVerification,
    inactiveStores,
  };
};

export const formatCurrencyINR = (val) => {
  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 0,
  }).format(val || 0);
};
